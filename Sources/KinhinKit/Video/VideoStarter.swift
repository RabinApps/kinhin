import Foundation

/// `kinhin video init`: a small starter config, so a first video is one command away.
public enum VideoStarter {
    /// What a new video file contains: three drawn scenes with a voice-over, so it builds with no recordings.
    public static func template(title: String) -> String {
        """
        # A kinhin video: scenes, a voice-over, a theme. Build it with: kinhin video build \(title)
        # Every field is explained in https://github.com/RabinApps/kinhin/blob/main/docs/videos-for-your-project.md
        name: \(title)
        theme: paper          # paper, clean, midnight, blueprint or chalk
        format: "16:9"        # 16:9, 9:16, 4:5 or 1:1
        voice: { engine: kokoro, name: af_heart }
        # music: { track: audio/bed.mp3, volume: 0.3 }   # a file in this repository (CC0 or yours)
        # captions: { burn: true, style: box }
        scenes:
          - id: intro
            type: title
            props: { title: "\(title)", subtitle: "Say what it does in one line" }
            narration: Meet \(title). Say what it does in one sentence.
          - id: why
            type: statement
            props: { text: "The problem, in plain words.", sub: "And what you do about it." }
            narration: Describe the problem your users have, and how this fixes it.
          - id: outro
            type: outro
            props: { line: "Try it today.", url: "example.com", facts: ["Open source", "No account needed"] }
            narration: Tell people where to go next.

        """
    }

    static let gitignore = "# Build output and the render cache: regenerated by `kinhin video build`.\nout/\n.cache/\n"

    /// The names a starter file may use: letters, digits, `-` and `_`, with `/` for folders.
    static func isAllowedName(_ name: String) -> Bool {
        VideoProjects.isValidName(name)
            && name.unicodeScalars.allSatisfy {
                CharacterSet.alphanumerics.contains($0) || "-_/".unicodeScalars.contains($0)
            }
    }

    /// Writes `<repo>/.kinhin/videos/<name>.yml` (and a `.gitignore` for the output beside it). Never overwrites.
    /// Returns the files written.
    @discardableResult
    public static func write(name: String, in repo: URL) throws -> [URL] {
        guard isAllowedName(name) else { throw VideoError.invalidName(name) }
        let directory = VideoProjects.directory(in: repo)
        if let existing = VideoProjects.file(named: name, in: repo) { throw VideoError.alreadyExists(existing.path) }
        let target = directory.appendingPathComponent(name).appendingPathExtension("yml")
        try FileManager.default.createDirectory(
            at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
        let title = name.split(separator: "/").last.map(String.init) ?? name
        try Data(template(title: title).utf8).write(to: target, options: .withoutOverwriting)
        var written = [target]
        let ignore = directory.appendingPathComponent(".gitignore")
        if !FileManager.default.fileExists(atPath: ignore.path) {
            try Data(gitignore.utf8).write(to: ignore, options: .withoutOverwriting)
            written.append(ignore)
        }
        return written
    }
}
