        encodedJitConfig = try c.decode(String.self, forKey: .encodedJitConfig)
    }

    enum CodingKeys: String, CodingKey {
        case encodedJitConfig = "encodedJITConfig"
    }
}

extension GitHubScaleSetStatistics: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        totalAssignedJobs = try c.decode(Int.self, forKey: .totalAssignedJobs)
        activeNodesCount =
            try c.decodeIfPresent(Int.self, forKey: .activeNodesCount)
            ?? c.decodeIfPresent(Int.self, forKey: .totalRunningJobs)
            ?? c.decodeIfPresent(Int.self, forKey: .totalBusyRunners)
            ?? 0
    }

    enum CodingKeys: String, CodingKey {
        case totalAssignedJobs = "totalAssignedJobs"
        case activeNodesCount = "activeNodesCount"
        case totalRunningJobs = "totalRunningJobs"
        case totalBusyRunners = "totalBusyRunners"
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(totalAssignedJobs, forKey: .totalAssignedJobs)
        try c.encode(activeNodesCount, forKey: .activeNodesCount)
    }
}

extension GitHubScaleSetJobEvent: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let messageType = try c.decode(String.self, forKey: .eventType)
        guard let kind = GitHubScaleSetJobEventKind(rawValue: messageType) else {
            throw DecodingError.dataCorruptedError(
                forKey: .eventType, in: c, debugDescription: "unsupported message type \(messageType)")
        }
        eventType = kind
        ownerName = try c.decode(String.self, forKey: .ownerName)
        repositoryName = try c.decode(String.self, forKey: .repositoryName)
        jobDisplayName = try c.decode(String.self, forKey: .jobDisplayName)
        requestLabels = try c.decodeIfPresent([String].self, forKey: .requestLabels) ?? []
        // the id arrives as a string or a number; the fallback below decodes the other shape
        if let string = try? c.decode(String.self, forKey: .runnerRequestId) {
            runnerRequestId = string
        } else {
            runnerRequestId = String(try c.decode(Int64.self, forKey: .runnerRequestId))
        }
        runnerName = try c.decodeIfPresent(String.self, forKey: .runnerName)
    }

    enum CodingKeys: String, CodingKey {
        case eventType = "messageType"
        case ownerName = "ownerName"
        case repositoryName = "repositoryName"
        case jobDisplayName = "jobDisplayName"
        case requestLabels = "requestLabels"
        case runnerRequestId = "runnerRequestId"
        case runnerName = "runnerName"
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(eventType, forKey: .eventType)
        try c.encode(ownerName, forKey: .ownerName)
        try c.encode(repositoryName, forKey: .repositoryName)
        try c.encode(jobDisplayName, forKey: .jobDisplayName)
        try c.encode(requestLabels, forKey: .requestLabels)
        try c.encode(runnerRequestId, forKey: .runnerRequestId)
        try c.encodeIfPresent(runnerName, forKey: .runnerName)
    }
}
