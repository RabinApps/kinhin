        }
        messageQueueUrl = url
        messageQueueAccessToken = try c.decode(String.self, forKey: .messageQueueAccessToken)
    }

    enum CodingKeys: String, CodingKey {
        case sessionId = "sessionId"
        case messageQueueUrl = "messageQueueUrl"
        case messageQueueAccessToken = "messageQueueAccessToken"
    }
}

