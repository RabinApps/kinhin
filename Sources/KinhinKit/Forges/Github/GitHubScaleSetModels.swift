import Foundation

// MARK: - Scale set admin + session DTOs

/// The response from `POST .../actions/runners/registration-token` followed by
/// the runner-registration exchange. This is the admin-token path the scale-set
/// client starts from.
public struct GitHubScaleSetRegistrationToken: Sendable, Equatable {
    public let token: String
    public let expiresAt: Date
    public let actionsUrl: URL

    public init(token: String, expiresAt: Date, actionsUrl: URL) {
        self.token = token
        self.expiresAt = expiresAt
        self.actionsUrl = actionsUrl
    }
}

/// A created or matched runner scale set.
public struct GitHubScaleSet: Sendable, Equatable {
    public let id: Int
    public let name: String
    public let runnerGroupName: String
    public let labels: [String]
    public let statistics: GitHubScaleSetStatistics?

    public init(
        id: Int, name: String, runnerGroupName: String, labels: [String],
        statistics: GitHubScaleSetStatistics? = nil
    ) {
        self.id = id
        self.name = name
        self.runnerGroupName = runnerGroupName
        self.labels = labels
        self.statistics = statistics
    }
}

/// A message-session handle returned when a session is created or refreshed.
public struct GitHubScaleSetSession: Sendable, Equatable {
    public let sessionId: String
    public let messageQueueUrl: URL
    public let messageQueueAccessToken: String

    public init(sessionId: String, messageQueueUrl: URL, messageQueueAccessToken: String) {
        self.sessionId = sessionId
        self.messageQueueUrl = messageQueueUrl
        self.messageQueueAccessToken = messageQueueAccessToken
    }
}

/// One message from the scale-set message queue.
public struct GitHubScaleSetMessage: Sendable, Equatable {
    public let messageId: String
    public let statistics: GitHubScaleSetStatistics?
    public let events: [GitHubScaleSetJobEvent]

    public init(messageId: String, statistics: GitHubScaleSetStatistics?, events: [GitHubScaleSetJobEvent]) {
        self.messageId = messageId
        self.statistics = statistics
        self.events = events
    }
}

/// JIT config generated by the scale-set endpoint for one runner.
public struct GitHubScaleSetJitConfig: Sendable, Equatable {
    public let encodedJitConfig: String

    public init(encodedJitConfig: String) {
        self.encodedJitConfig = encodedJitConfig
    }
}

// MARK: - Statistics + job messages

/// Statistics the listener scales on.
public struct GitHubScaleSetStatistics: Sendable, Equatable {
    public let totalAssignedJobs: Int
    public let activeNodesCount: Int

    public init(totalAssignedJobs: Int, activeNodesCount: Int) {
        self.totalAssignedJobs = totalAssignedJobs
        self.activeNodesCount = activeNodesCount
    }
}

/// A job lifecycle event delivered through the message session.
public enum GitHubScaleSetJobEventKind: String, Sendable, Equatable, Codable {
    case jobAvailable = "JobAvailable"
    case jobAssigned = "JobAssigned"
    case jobStarted = "JobStarted"
    case jobCompleted = "JobCompleted"
}

public struct GitHubScaleSetJobEvent: Sendable, Equatable {
    public let ownerName: String
    public let repositoryName: String
    public let jobDisplayName: String
    public let requestLabels: [String]
    public let runnerRequestId: String
    public let eventType: GitHubScaleSetJobEventKind
    /// The runner that took the job (`JobStarted`, `JobCompleted`); absent on earlier events.
    public let runnerName: String?

    public init(
        ownerName: String, repositoryName: String, jobDisplayName: String, requestLabels: [String],
        runnerRequestId: String, eventType: GitHubScaleSetJobEventKind, runnerName: String? = nil
    ) {
        self.ownerName = ownerName
        self.repositoryName = repositoryName
        self.jobDisplayName = jobDisplayName
        self.requestLabels = requestLabels
        self.runnerRequestId = runnerRequestId
        self.eventType = eventType
        self.runnerName = runnerName
    }
}

// MARK: - Codable DTOs for the wire

extension GitHubScaleSetRegistrationToken: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        token = try c.decode(String.self, forKey: .token)
        expiresAt =
            try c.decodeIfPresent(Date.self, forKey: .expiresAt)
            ?? Self.expirationDate(from: token)
            ?? .now
        let urlString = try c.decode(String.self, forKey: .actionsUrl)
        guard let url = URL(string: urlString) else {
            throw DecodingError.dataCorruptedError(forKey: .actionsUrl, in: c, debugDescription: "invalid URL")
        }
        actionsUrl = url
    }

    enum CodingKeys: String, CodingKey {
        case token
        case expiresAt = "expires_at"
        case actionsUrl = "url"
    }

    private static func expirationDate(from token: String) -> Date? {
        struct Claims: Decodable { let exp: TimeInterval }
        let parts = token.split(separator: ".", omittingEmptySubsequences: false)
        guard parts.count == 3 else { return nil }
        var payload = String(parts[1]).replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
        payload += String(repeating: "=", count: (4 - payload.count % 4) % 4)
        guard let data = Data(base64Encoded: payload),
            // an undecodable token payload has no expiry to read; the caller treats nil as "refresh it"
            let claims = try? JSONDecoder().decode(Claims.self, from: data)
        else { return nil }
        return Date(timeIntervalSince1970: claims.exp)
    }
}

extension GitHubScaleSet: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(Int.self, forKey: .id)
        name = try c.decode(String.self, forKey: .name)
        runnerGroupName = try c.decodeIfPresent(String.self, forKey: .runnerGroupName) ?? "default"
        // labels arrive as plain strings or as {name} objects; the fallback below decodes the other shape
        if let plainLabels = try? c.decode([String].self, forKey: .labels) {
            labels = plainLabels
        } else {
            labels = try c.decodeIfPresent([ScaleSetLabel].self, forKey: .labels)?.map(\.name) ?? []
        }
        statistics = try c.decodeIfPresent(GitHubScaleSetStatistics.self, forKey: .statistics)
    }

    enum CodingKeys: String, CodingKey {
        case id
        case name
        case runnerGroupName = "runnerGroupName"
        case labels
        case statistics
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(name, forKey: .name)
        try c.encode(runnerGroupName, forKey: .runnerGroupName)
        try c.encode(labels.map { ScaleSetLabel(name: $0, type: "System") }, forKey: .labels)
        try c.encodeIfPresent(statistics, forKey: .statistics)
    }
}

private struct ScaleSetLabel: Codable {
    let name: String
    let type: String
}

extension GitHubScaleSetSession: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        sessionId = try c.decode(String.self, forKey: .sessionId)
        let urlString = try c.decode(String.self, forKey: .messageQueueUrl)
