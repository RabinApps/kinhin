#!/usr/bin/env node
// Turns out/voice-timings.json (from voice.mjs) into the timeline of the cut:
//   src/timing.ts         scene lengths the Motion Canvas scenes hold for (commit it; the scenes import it)
//   out/timeline.json     every scene's start, length and cues on the final clock (assemble.mjs reads it)
//   captions/launch.srt   the narration as captions on the final clock
// A scene lasts as long as the longer of its own animation (`minLength` in script/launch.json) and its speech
// plus `tail` seconds, so the picture follows the voice and never the other way round.
// Usage: node scripts/retime.mjs [script.json]
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const script = JSON.parse(readFileSync(resolve(process.argv[2] ?? join(root, 'script/launch.json')), 'utf8'));
const voice = JSON.parse(readFileSync(join(root, 'out/voice-timings.json'), 'utf8'));
const round = (x) => Math.round(x * 100) / 100;

let cursor = 0;
const scenes = {};
const srt = [];
for (const scene of script.scenes) {
  const spoken = voice.scenes[scene.id];
  if (!spoken) throw new Error(`no voice timings for "${scene.id}"; run scripts/voice.mjs`);
  const length = round(Math.max(scene.minLength ?? 0, spoken.speechEnd + (script.tail ?? 0.8)));
  scenes[scene.id] = {start: round(cursor), length, cues: spoken.cues};
  for (const cue of spoken.cues) srt.push({start: cursor + cue.start, end: cursor + cue.end, text: cue.text});
  cursor += length;
}

const stamp = (s) => {
  const ms = Math.round(s * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
};
// Break a long caption in two at the comma or word nearest its middle.
const wrap = (text) => {
  if (text.length <= 44) return text;
  const words = text.split(' ');
  let best = 1;
  let bestGap = Infinity;
  for (let i = 1; i < words.length; i++) {
    const left = words.slice(0, i).join(' ').length;
    const gap = Math.abs(left - text.length / 2) - (words[i - 1].endsWith(',') ? 6 : 0);
    if (gap < bestGap) [best, bestGap] = [i, gap];
  }
  return `${words.slice(0, best).join(' ')}\n${words.slice(best).join(' ')}`;
};
writeFileSync(
  join(root, 'captions/launch.srt'),
  srt.map((c, i) => `${i + 1}\n${stamp(c.start)} --> ${stamp(c.end)}\n${wrap(c.text)}\n`).join('\n'),
);
writeFileSync(join(root, 'out/timeline.json'), JSON.stringify({total: round(cursor), voice: voice.voice, scenes}, null, 2) + '\n');

const ts = Object.entries(scenes)
  .map(([id, s]) => `  ${id}: ${s.length},`)
  .join('\n');
writeFileSync(
  join(root, 'src/timing.ts'),
  `// Generated by scripts/retime.mjs from the voice-over: how long each title scene lasts, in seconds.\n` +
    `// Edit script/launch.json and re-run the script instead of changing these by hand.\n` +
    `export const timing = {\n${ts}\n};\n`,
);
console.log(Object.entries(scenes).map(([id, s]) => `${id.padEnd(9)} ${String(s.start).padStart(6)}s +${s.length}s`).join('\n'));
console.log(`total ${round(cursor)}s`);
